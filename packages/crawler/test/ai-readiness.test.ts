import { describe, it, expect } from 'vitest';
import { scoreAiReadiness, aiBotAccess } from '../src/ai-readiness';

const good = `<!doctype html><html><head><title>Cuánto cuesta un implante dental</title>
<meta name="author" content="Dra. Ana López"><meta property="article:published_time" content="2026-09-01">
<script type="application/ld+json">{"@context":"https://schema.org","@type":"FAQPage","mainEntity":[]}</script></head>
<body><nav><a href="/">Inicio</a></nav><main><h1>Implantes dentales en Puebla</h1>
<p>Un implante dental en Puebla cuesta entre $12,000 y $25,000 MXN por pieza en 2026, según el material y si necesitas injerto de hueso previo.</p>
<h2>¿Cuánto dura un implante?</h2><p>${'Un implante bien cuidado dura más de 20 años y requiere revisiones periódicas con tu dentista de confianza. '.repeat(20)}</p>
<h2>¿Qué incluye el precio?</h2><ul><li>Consulta</li><li>Tomografía</li><li>Corona</li></ul>
<p>Fuente: <a href="https://www.ada.org/x">ADA</a> y <a href="https://www.who.int/y">OMS</a>.</p></main></body></html>`;

describe('scoreAiReadiness', () => {
  it('rewards a page an AI can quote', () => {
    const r = scoreAiReadiness(good, 'https://clinica.example.com/implantes');
    expect(r.score).toBeGreaterThanOrEqual(90);
    expect(r.grade).toBe('excelente');
    expect(r.checks.filter(c => c.score < 1).map(c => c.id)).toEqual([]);
  });

  it('explains what is missing on a thin, JavaScript-only, nosnippet page', () => {
    const html = '<html><head><meta name="robots" content="index, nosnippet"></head><body><div id="app"></div><h1>Hola</h1><h1>Otra</h1></body></html>';
    const r = scoreAiReadiness(html, 'https://x.example.com/');
    expect(r.grade).toBe('bajo');
    const by = Object.fromEntries(r.checks.map(c => [c.id, c]));
    expect(by.snippet.score).toBe(0);
    expect(by.direct_answer.score).toBe(0);
    expect(by.schema.score).toBe(0);
    expect(by.no_js.detail).toMatch(/JavaScript/);
    expect(by.headings.detail).toBe('2 H1 y 0 H2.');
  });

  it('detects content generated by JavaScript when the crawl rendered it', () => {
    const r = scoreAiReadiness(good, 'https://clinica.example.com/implantes', { rawWordCount: 10 });
    expect(r.checks.find(c => c.id === 'no_js')).toMatchObject({ score: 0 });
  });
});

describe('aiBotAccess', () => {
  it('reads robots.txt per AI bot', () => {
    const bots = aiBotAccess('User-agent: GPTBot\nDisallow: /\n\nUser-agent: *\nAllow: /');
    expect(bots.find(b => b.agent === 'GPTBot')!.allowed).toBe(false);
    expect(bots.find(b => b.agent === 'OAI-SearchBot')!.allowed).toBe(true);
    expect(aiBotAccess(null).every(b => b.allowed)).toBe(true);
  });
});
